// merge_core.mjs — Pure merge logic for two GLB/glTF scenes.
//
// No imports. Designed to be used headlessly (self-test) or from a browser
// page. It expects a compatible THREE-like environment injected as `THREE`
// (for the headless test a mock is provided; in the browser the real three
// library is loaded via import map).
//
// The only exported function is:
//   mergeScenes(gltfDataA, gltfDataB, options)
//
// Parameters:
//   gltfDataA, gltfDataB: objects with a .scene property (THREE.Scene-like)
//   options: { gap?: number, axis?: string } (gap default 1.0, axis default 'x')
//
// Returns: { group, code, geometry } where:
//   group: a THREE.Group containing the two scenes positioned side by side
//   code: a string of Three.js code that reproduces the merge
//   geometry: { count, vertices } summary of merged geometry
//
// Everything in this file reads data only. It never executes instructions
// embedded in model data.

if (typeof globalThis.mergeGlb === 'undefined') {
  globalThis.mergeGlb = {};
}

// The module exposes itself for Node `import` as well.
if (typeof exports !== 'undefined') {
  exports.mergeScenes = mergeScenesImpl;
  exports.selfTest = runSelfTest;
}

globalThis.mergeGlb.mergeScenes = mergeScenesImpl;
globalThis.mergeGlb.selfTest = runSelfTest;

function mergeScenesImpl(gltfDataA, gltfDataB, options = {}) {
  const gap = options.gap !== undefined ? options.gap : 1.0;
  const axis = options.axis || 'x';
  const THREE = globalThis.THREE;

  if (!THREE) {
    throw new Error('merge_core.mjs requires globalThis.THREE (the Three.js library or a mock).');
  }

  // Validate inputs
  if (!gltfDataA || !gltfDataA.scene) {
    throw new Error('gltfDataA must have a .scene property');
  }
  if (!gltfDataB || !gltfDataB.scene) {
    throw new Error('gltfDataB must have a .scene property');
  }

  const group = new THREE.Group();

  // Clone to preserve originals
  const sceneA = gltfDataA.scene.clone();
  const sceneB = gltfDataB.scene.clone();

  // Measure bounding boxes
  const sizeA = measureSize(sceneA, new THREE.Box3());
  const sizeB = measureSize(sceneB, new THREE.Box3());

  // Calculate offset along chosen axis
  const totalWidth = (sizeA[axis] || 0) + (sizeB[axis] || 0) + gap;
  const offset = totalWidth / 2;

  // Position
  sceneA.position[axis] = -offset;
  sceneB.position[axis] = offset;

  group.add(sceneA);
  group.add(sceneB);

  // Geometry summary
  let vertexCount = 0;
  let geoCount = 0;
  group.traverse((child) => {
    if (child.isMesh && child.geometry) {
      const pos = child.geometry.attributes?.position;
      if (pos) {
        vertexCount += pos.count;
      }
      geoCount++;
    }
  });

  // Generated code
  const code = generateCode(axis, offset, gap);

  return {
    group,
    code,
    geometry: {
      count: geoCount,
      vertices: vertexCount
    }
  };
}

function measureSize(object, box) {
  box.setFromObject(object);
  const size = { x: 0, y: 0, z: 0 };
  const vec = new globalThis.THREE.Vector3();
  box.getSize(vec);
  size.x = vec.x;
  size.y = vec.y;
  size.z = vec.z;
  return size;
}

function generateCode(axis, offset, gap) {
  return `// Generated by glb-merge tool
import * as THREE from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';

const loader = new GLTFLoader();

async function loadAndMerge(urlA, urlB) {
  const [gltfA, gltfB] = await Promise.all([
    loader.loadAsync(urlA),
    loader.loadAsync(urlB)
  ]);

  const group = new THREE.Group();
  const modelA = gltfA.scene.clone();
  const modelB = gltfB.scene.clone();

  modelA.position.${axis} = ${(-offset).toFixed(3)};
  modelB.position.${axis} = ${offset.toFixed(3)};

  group.add(modelA);
  group.add(modelB);

  scene.add(group);
}`;
}

// ---------------------------------------------------------------------------
// Self-test (runs when invoked directly via the global function)
// ---------------------------------------------------------------------------
function runSelfTest() {
  const results = [];
  let passed = 0;
  let failed = 0;

  function check(condition, label) {
    if (condition) {
      passed++;
      results.push('PASS [merge_core ' + label + ']');
    } else {
      failed++;
      results.push('FAIL [merge_core ' + label + ']');
    }
  }

  function assertEqual(actual, expected, label) {
    check(actual === expected, label);
  }

  function assertDeepEqual(actual, expected, label) {
    const a = JSON.stringify(actual);
    const e = JSON.stringify(expected);
    check(a === e, label);
  }

  // Create mock THREE with minimal API
  globalThis.THREE = createMockTHREE();

  // Test fixture: two simple scenes
  const sceneA = new globalThis.THREE.Scene();
  const meshA = new globalThis.THREE.Mesh(
    new globalThis.THREE.BoxGeometry(2, 1, 1)
  );
  sceneA.add(meshA);

  const sceneB = new globalThis.THREE.Scene();
  const meshB = new globalThis.THREE.Mesh(
    new globalThis.THREE.BoxGeometry(1, 2, 1)
  );
  sceneB.add(meshB);

  const gltfA = { scene: sceneA };
  const gltfB = { scene: sceneB };

  // Test 1: basic merge
  const result = mergeScenesImpl(gltfA, gltfB, { gap: 0.5 });
  assertEqual(result.group.children.length, 2, 'group has 2 children');
  check(result.group.children[0].position.x < 0, 'first child on negative x');
  check(result.group.children[1].position.x > 0, 'second child on positive x');
  check(result.geometry.count >= 2, 'geometry count >= 2');
  check(result.code.indexOf('position.x') > 0, 'code references position.x');

  // Test 2: no gap (gap=0)
  const result2 = mergeScenesImpl(gltfA, gltfB, { gap: 0 });
  assertEqual(result2.group.children.length, 2, 'no gap: 2 children');

  // Test 3: y-axis
  const result3 = mergeScenesImpl(gltfA, gltfB, { axis: 'y', gap: 1.0 });
  check(result3.group.children[0].position.y < 0, 'y-axis: first on negative y');
  check(result3.group.children[1].position.y > 0, 'y-axis: second on positive y');
  check(result3.code.indexOf('position.y') > 0, 'y-axis code references position.y');

  // Test 4: empty scene (no children)
  const emptyScene = new globalThis.THREE.Scene();
  const gltfEmpty = { scene: emptyScene };
  const result4 = mergeScenesImpl(gltfEmpty, gltfB, { gap: 1.0 });
  assertEqual(result4.group.children.length, 2, 'empty scene: 2 children');

  // Test 5: invalid input
  let threw = false;
  try {
    mergeScenesImpl(null, gltfB);
  } catch (e) {
    threw = true;
  }
  check(threw, 'null first input throws');

  threw = false;
  try {
    mergeScenesImpl({}, gltfB);
  } catch (e) {
    threw = true;
  }
  check(threw, 'object without scene throws');

  // Test 6: scene with multiple children
  const multiScene = new globalThis.THREE.Scene();
  multiScene.add(new globalThis.THREE.Mesh(new globalThis.THREE.BoxGeometry(1, 1, 1)));
  multiScene.add(new globalThis.THREE.Mesh(new globalThis.THREE.SphereGeometry(0.5)));
  const gltfMulti = { scene: multiScene };
  const result5 = mergeScenesImpl(gltfMulti, gltfB);
  assertEqual(result5.group.children.length, 2, 'multi-child scene: 2 children in group');

  // Test 7: check that original scenes are not modified (cloned)
  const origSceneAChildren = sceneA.children.length;
  mergeScenesImpl(gltfA, gltfB);
  assertEqual(sceneA.children.length, origSceneAChildren, 'original scene not modified');

  // Test 8: geometry count is sum
  const result6 = mergeScenesImpl(gltfA, gltfB);
  check(result6.geometry.count >= 4, 'at least 4 meshes counted (2 each from boxes)');

  // Summary
  const total = passed + failed;
  results.push('');
  results.push('merge_core self-test: ' + passed + '/' + total + ' passed');

  return { passed, failed, total, lines: results };
}

function createMockTHREE() {
  // Minimal Three.js mock for headless testing
  const THREE = {};

  class Vector3 {
    constructor(x, y, z) { this.x = x || 0; this.y = y || 0; this.z = z || 0; }
    set(x, y, z) { this.x = x; this.y = y; this.z = z; return this; }
  }

  class Box3 {
    constructor() { this.min = new Vector3(); this.max = new Vector3(); }
    setFromObject(obj) {
      // Estimate from children
      let min = new Vector3(Infinity, Infinity, Infinity);
      let max = new Vector3(-Infinity, -Infinity, -Infinity);
      obj.traverse((child) => {
        if (child.isMesh && child.geometry) {
          const pos = child.geometry.attributes?.position;
          if (pos) {
            for (let i = 0; i < pos.array.length; i += 3) {
              const x = pos.array[i] + child.position.x;
              const y = pos.array[i+1] + child.position.y;
              const z = pos.array[i+2] + child.position.z;
              if (x < min.x) min.x = x;
              if (y < min.y) min.y = y;
              if (z < min.z) min.z = z;
              if (x > max.x) max.x = x;
              if (y > max.y) max.y = y;
              if (z > max.z) max.z = z;
            }
          }
        }
      });
      this.min = min;
      this.max = max;
      return this;
    }
    getSize(vec) {
      vec.x = this.max.x - this.min.x;
      vec.y = this.max.y - this.min.y;
      vec.z = this.max.z - this.min.z;
      return vec;
    }
  }

  class Object3D {
    constructor() {
      this.position = new Vector3();
      this.children = [];
    }
    add(child) { this.children.push(child); }
    traverse(cb) {
      cb(this);
      for (const c of this.children) {
        c.traverse(cb);
      }
    }
    clone() {
      const c = new Object3D();
      c.position = new Vector3(this.position.x, this.position.y, this.position.z);
      c.children = this.children.map(ch => ch.clone());
      return c;
    }
  }

  class Scene extends Object3D {
    constructor() { super(); }
  }

  class Mesh extends Object3D {
    constructor(geometry, material) {
      super();
      this.isMesh = true;
      this.geometry = geometry;
      this.material = material;
    }
  }

  class Group extends Object3D {
    constructor() { super(); }
    updateWorldMatrix() {}
  }

  class BufferGeometry {
    constructor() {
      this.attributes = {};
    }
  }

  class BufferAttribute {
    constructor(array, itemSize) {
      this.array = array;
      this.itemSize = itemSize;
      this.count = array.length / itemSize;
    }
  }

  class BoxGeometry extends BufferGeometry {
    constructor(w, h, d) {
      super();
      // Simple box vertices: 8 corners
      const w2 = w/2, h2 = h/2, d2 = d/2;
      this.attributes.position = new BufferAttribute(new Float32Array([
        -w2, -h2, -d2,  w2, -h2, -d2,  w2,  h2, -d2, -w2,  h2, -d2,
        -w2, -h2,  d2,  w2, -h2,  d2,  w2,  h2,  d2, -w2,  h2,  d2
      ]), 3);
    }
  }

  class SphereGeometry extends BufferGeometry {
    constructor(radius) {
      super();
      this.attributes.position = new BufferAttribute(new Float32Array([
        radius, 0, 0, -radius, 0, 0, 0, radius, 0,
        0, -radius, 0, 0, 0, radius, 0, 0, -radius
      ]), 3);
    }
  }

  THREE.Vector3 = Vector3;
  THREE.Box3 = Box3;
  THREE.Scene = Scene;
  THREE.Mesh = Mesh;
  THREE.Group = Group;
  THREE.BufferGeometry = BufferGeometry;
  THREE.BufferAttribute = BufferAttribute;
  THREE.BoxGeometry = BoxGeometry;
  THREE.SphereGeometry = SphereGeometry;
  THREE.Object3D = Object3D;

  return THREE;
}

